# frozen_string_literal: true

module Types
  module Ai
    class GenerationSubFlowValueType < Types::BaseObject
      description 'Represents a sub-flow value generated by AI.'

      field :description, String,
            null: true,
            description: 'The generated sub-flow description.'
      field :function_definition, Types::FunctionDefinitionType,
            null: true,
            description: 'Resolved function definition for the generated sub-flow.'
      field :name, String,
            null: true,
            description: 'The generated sub-flow name.'
      field :parameters, [Types::Ai::GenerationSubFlowParameterType],
            null: false,
            description: 'The generated sub-flow parameters.'
      field :signature, String,
            null: true,
            description: 'The generated sub-flow signature.'
      field :starting_node_id, Types::GlobalIdType[::NodeFunction],
            null: true,
            description: 'The generated sub-flow starting node ID.'

      def starting_node_id
        Sagittarius::Utils.generated_global_id(object[:starting_node_id] || object['starting_node_id'], ::NodeFunction)
      end
    end
  end
end
